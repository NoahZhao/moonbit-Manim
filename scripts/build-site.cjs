#!/usr/bin/env node
'use strict';

// Regenerate the committed browser runtime. Pages serves site/ without a toolchain.
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const { execFileSync } = require('node:child_process');
const root = path.resolve(__dirname, '..');
const site = path.join(root, 'site');
execFileSync('moon', ['build', 'src/cmd/web', '--target', 'js', '--release', '--deny-warn'], { cwd: root, stdio: 'inherit' });
const runtime = path.join(root, '_build/js/release/build/cmd/web/web.js');
const banner = '/*! MoonManim browser engine · MIT License. Generated by npm run site:build; edit src/cmd/web/main.mbt. */\n';
fs.mkdirSync(path.join(site, 'assets/licenses'), { recursive: true });
fs.writeFileSync(path.join(site, 'assets/engine.js'), banner + fs.readFileSync(runtime, 'utf8'));
fs.copyFileSync(path.join(root, 'LICENSE'), path.join(site, 'LICENSE.txt'));
for (const file of ['NOTICE.md', 'MATHJAX-LICENSE.txt']) {
  fs.copyFileSync(path.join(root, 'assets/tex', file), path.join(site, 'assets/licenses', file));
}
console.log('Site runtime and license notices updated in site/.');

// Project covers come from the exact browser engine shipped with the website.
const context = vm.createContext({ console });
vm.runInContext(fs.readFileSync(path.join(site, 'assets/engine.js'), 'utf8'), context);
const projects = [
  ['tangent', 0.25, -1.5, 2, 0],
  ['lissajous', 0.85, 3, 2, 90],
  ['matrix', 1, 1, 1.5, 15],
  ['bezier', 0.75, 2.6, -2.6, 0],
  ['pythagoras', 1, 2, 3, 0],
  ['morph', 0.45, 0, 0, 0.3],
];
fs.mkdirSync(path.join(site, 'assets/projects'), { recursive: true });
for (const [name, ...parameters] of projects) {
  const result = JSON.parse(context.MoonManim.render(name, ...parameters));
  if (result.error || !result.svg || /NaN|Infinity/.test(result.svg)) throw new Error('Invalid project cover: ' + name);
  fs.writeFileSync(path.join(site, 'assets/projects', name + '.svg'), result.svg);
}
console.log('Generated six mathematical project covers.');

if (process.argv.includes('--media')) {
  const sharp = require('sharp');
  const demos = [
    ['dynamics/01-tangent.mp4', 'tangent', 7],
    ['cnn/01-cnn.mp4', 'cnn', 4],
    ['cnn/02-cnn-pooling.mp4', 'cnn-pooling', 5],
    ['lessons/01-quadratic.mp4', 'quadratic', 13],
    ['lessons/02-linear-algebra.mp4', 'matrix', 14],
    ['lessons/03-pythagoras.mp4', 'pythagoras', 19],
    ['videos/01-geometry.mp4', 'geometry', 5],
    ['videos/02-path-creation.mp4', 'bezier', 5],
    ['videos/03-group-transforms.mp4', 'groups', 6],
  ];
  const directory = path.join(site, 'assets/demos');
  fs.mkdirSync(directory, { recursive: true });
  (async () => {
    for (const [source, name, second] of demos) {
      const input = path.join(root, 'output', source);
      if (!fs.existsSync(input)) throw new Error(`Missing ${input}. Generate demo videos first; see docs/website.zh-CN.md.`);
      fs.copyFileSync(input, path.join(directory, `${name}.mp4`));
      const png = execFileSync(process.env.MOONMANIM_FFMPEG || 'ffmpeg', ['-loglevel', 'error', '-ss', String(second), '-i', input, '-frames:v', '1', '-f', 'image2pipe', '-vcodec', 'png', '-'], { maxBuffer: 20 * 1024 * 1024 });
      await sharp(png).resize(800).webp({ quality: 85 }).toFile(path.join(directory, `${name}.webp`));
      console.log(`Prepared ${name}.mp4 and poster.`);
    }
    const social = fs.readFileSync(path.join(site, 'assets/social.svg'));
    await sharp(social).png().toFile(path.join(site, 'assets/social.png'));
  })().catch((error) => { console.error(error.message); process.exitCode = 1; });
}
