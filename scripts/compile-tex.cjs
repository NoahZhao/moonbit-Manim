#!/usr/bin/env node
'use strict';

// Build-time TeX layout only. MoonBit owns all runtime geometry and animation.
const fs = require('node:fs/promises');
const path = require('node:path');
const { mathjax } = require('mathjax-full/js/mathjax.js');
const { TeX } = require('mathjax-full/js/input/tex.js');
const { SVG } = require('mathjax-full/js/output/svg.js');
const { liteAdaptor } = require('mathjax-full/js/adaptors/liteAdaptor.js');
const { RegisterHTMLHandler } = require('mathjax-full/js/handlers/html.js');
const { AllPackages } = require('mathjax-full/js/input/tex/AllPackages.js');
const svgpath = require('svgpath');

const root = path.resolve(__dirname, '..');
const adaptor = liteAdaptor();
RegisterHTMLHandler(adaptor);
const document = mathjax.document('', {
  InputJax: new TeX({ packages: AllPackages, formatError: (_jax, error) => { throw error; } }),
  OutputJax: new SVG({ fontCache: 'none' }),
});

function cubics(data, transform) {
  const p = svgpath(data).unshort().unarc().abs().transform(transform).scale(0.001, -0.001);
  if (p.err) throw new Error(p.err);
  p.iterate(() => {}); // Materialize svgpath's lazy affine stack.
  const contours = [];
  let x = 0, y = 0, sx = 0, sy = 0, segments = [];
  const add = (c1x, c1y, c2x, c2y, ex, ey) => {
    segments.push([x, y, c1x, c1y, c2x, c2y, ex, ey]);
    x = ex; y = ey;
  };
  const line = (ex, ey) => add(x + (ex - x) / 3, y + (ey - y) / 3,
    x + (ex - x) * 2 / 3, y + (ey - y) * 2 / 3, ex, ey);
  const finish = closed => {
    if (segments.length) contours.push({ closed, segments });
    segments = [];
  };
  for (const s of p.segments) {
    switch (s[0]) {
      case 'M': finish(false); x = sx = s[1]; y = sy = s[2]; break;
      case 'L': line(s[1], s[2]); break;
      case 'H': line(s[1], y); break;
      case 'V': line(x, s[1]); break;
      case 'C': add(...s.slice(1)); break;
      case 'Q': add(x + (s[1] - x) * 2 / 3, y + (s[2] - y) * 2 / 3,
        s[3] + (s[1] - s[3]) * 2 / 3, s[4] + (s[2] - s[4]) * 2 / 3, s[3], s[4]); break;
      case 'Z': case 'z': if (x !== sx || y !== sy) line(sx, sy); finish(true); break;
      default: throw new Error('Unsupported MathJax path command: ' + s[0]);
    }
  }
  finish(false);
  return contours;
}

function glyph(tex) {
  const container = document.convert(tex, { display: true });
  const svg = adaptor.childNodes(container).find(n => adaptor.kind(n) === 'svg');
  if (!svg) throw new Error('No SVG for ' + tex);
  const viewBox = adaptor.getAttribute(svg, 'viewBox').split(/\s+/).map(Number);
  const contours = [];
  const visit = (node, transforms) => {
    const kind = adaptor.kind(node);
    if (kind === '#text' || kind === '#comment') return;
    if (adaptor.getAttribute(node, 'data-mml-node') === 'merror') throw new Error('Invalid TeX: ' + tex);
    const own = adaptor.getAttribute(node, 'transform');
    const chain = own ? [...transforms, own] : transforms;
    let d;
    if (kind === 'path') d = adaptor.getAttribute(node, 'd');
    else if (kind === 'rect') {
      const attr = name => Number(adaptor.getAttribute(node, name) || 0);
      const [x, y, w, h] = ['x', 'y', 'width', 'height'].map(attr);
      d = `M${x} ${y}h${w}v${h}h${-w}z`;
    } else if (!['svg', 'g', 'title', 'desc'].includes(kind)) {
      throw new Error('Unsupported MathJax element: ' + kind);
    }
    if (d) contours.push(...cubics(d, chain.join(' ')));
    if (!['title', 'desc'].includes(kind)) for (const child of adaptor.childNodes(node)) visit(child, chain);
  };
  visit(svg, []);
  if (!Number.isFinite(viewBox[2]) || viewBox[2] <= 0 || !contours.length) throw new Error('Empty TeX fragment: ' + tex);
  return { tex, advance: viewBox[2] / 1000, contours };
}

async function main() {
  const args = process.argv.slice(2);
  if (args.length !== 0 && args.length !== 2) throw new Error('Usage: node scripts/compile-tex.cjs [fragments.json assets.json]');
  const input = path.resolve(args[0] || path.join(root, 'assets/tex/fragments.json'));
  const output = path.resolve(args[1] || path.join(root, 'assets/tex/teaching.json'));
  const fragments = JSON.parse(await fs.readFile(input, 'utf8'));
  if (!Array.isArray(fragments) || fragments.some(t => typeof t !== 'string' || !t)) throw new Error('Expected an array of TeX source strings');
  const asset = { version: 1, glyphs: [...new Set(fragments)].map(glyph) };
  const json = JSON.stringify(asset).replaceAll('],[', '],\n[').replaceAll('},{"tex"', '},\n{"tex"');
  await fs.mkdir(path.dirname(output), { recursive: true });
  await fs.writeFile(output, json + '\n');
  if (args.length === 0) {
    await fs.mkdir(path.join(root, 'src/teaching'), { recursive: true });
    await fs.writeFile(path.join(root, 'src/teaching/assets.generated.mbt'),
      '///|\n// Generated by scripts/compile-tex.cjs; do not edit.\npub fn tex_assets() -> String {\n  (\n' + json.split('\n').map(line => '    #|' + line).join('\n') + '\n  )\n}\n');
  }
  console.log(`Compiled ${asset.glyphs.length} TeX fragments -> ${output}`);
}
main().catch(error => { console.error(error); process.exitCode = 1; });
